export function objectConstructorKeys(): string[] {
    const keys = ["length", "name", "prototype"];
    for (const method of objectMethods) {
        keys.push(method.name);
    }
    return keys;
}

export function prototypeMethodLength(name: string, numberPrototype: boolean): number {
    if (name === "toString") {
        return numberPrototype ? 1 : 0;
    }
    if (
        [
            "substring",
            "substr",
            "copyWithin",
            "replace",
            "replaceAll",
            "split",
            "toSpliced",
            "with",
            "slice",
            "apply",
            "splice",
            "__defineGetter__",
            "__defineSetter__",
        ].includes(name)
    ) {
        return 2;
    }
    if (
        [
            "padStart",
            "padEnd",
            "fill",
            "repeat",
            "toFixed",
            "toExponential",
            "toPrecision",
            "flatMap",
            "toSorted",
            "sort",
            "anchor",
            "fontcolor",
            "fontsize",
            "link",
            "localeCompare",
            "concat",
            "propertyIsEnumerable",
            "isPrototypeOf",
            "hasOwnProperty",
            "__lookupGetter__",
            "__lookupSetter__",
            "call",
            "bind",
            "join",
            "push",
            "unshift",
            "at",
            "lastIndexOf",
            "indexOf",
            "includes",
            "match",
            "search",
            "matchAll",
            "filter",
            "map",
            "forEach",
            "reduce",
            "reduceRight",
            "find",
            "findIndex",
            "findLast",
            "findLastIndex",
            "every",
            "some",
            "charAt",
            "charCodeAt",
            "codePointAt",
            "startsWith",
            "endsWith",
        ].includes(name)
    ) {
        return 1;
    }
    if (
        [
            "valueOf",
            "toLocaleString",
            "pop",
            "shift",
            "reverse",
            "toReversed",
            "flat",
            "trim",
            "trimStart",
            "trimEnd",
            "trimLeft",
            "trimRight",
            "toLowerCase",
            "toLocaleLowerCase",
            "toUpperCase",
            "toLocaleUpperCase",
            "normalize",
            "keys",
            "values",
            "entries",
            "big",
            "blink",
            "bold",
            "fixed",
            "italics",
            "small",
            "strike",
            "sub",
            "sup",
            "isWellFormed",
            "toWellFormed",
        ].includes(name)
    ) {
        return 0;
    }
    throw new Error("missing expected prototype arity: " + name);
}
