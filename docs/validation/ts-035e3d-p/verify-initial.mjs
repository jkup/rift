import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
const here=dirname(fileURLToPath(import.meta.url)),root=resolve(here,'../../../..');
const read=p=>JSON.parse(readFileSync(resolve(here,p)));
const sha=b=>createHash('sha256').update(b).digest('hex');
const baseline=read('baseline.json');
for(const f of baseline.files){const b=readFileSync(resolve(root,f.path));assert.equal(b.length,f.bytes,f.path);assert.equal(sha(b),f.sha256,f.path);}
const original=execFileSync('git',['show',baseline.base+':typescript/TASKS.md'],{cwd:root,encoding:'utf8',maxBuffer:4*1024*1024});
const current=readFileSync(resolve(root,'typescript/TASKS.md'),'utf8');
const heading='### TS-035E3d-P - Conformance host services and preflight contract design';
assert.equal(current.split(heading)[0],original.split(heading)[0],'other task sections');
for(const f of read('closure-audit.json').originalInputs)assert.equal(sha(Buffer.from(f.originalBase64,'base64')),f.sha256,f.path);
const manifest=read('proposal-manifest.json');
const producer=readFileSync(resolve(root,'typescript/src/script-observation.ts'),'utf8');
const start=producer.indexOf('// BEGIN private positional conformance request construction.');
const marker='// END private positional conformance request construction.';
const end=producer.indexOf(marker)+marker.length;
assert(start>=0&&end>start);
assert.equal(readFileSync(resolve(here,'producer-boundary.mts'),'utf8'),producer.slice(start,end),'exact reduced source span');
assert.deepEqual(manifest.replacements,[]);assert.deepEqual(manifest.additions,[]);
assert.equal(manifest.implementationAuthorized,false);
for(const f of manifest.evidence)assert.equal(sha(readFileSync(resolve(here,f.path))),f.sha256,f.path);
console.log(JSON.stringify({protectedFiles:baseline.files.length,evidenceFiles:manifest.evidence.length,implementationAuthorized:false,passed:true}));
