import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {writeFileSync} from 'node:fs';
import {probeVerdict} from '../../../tools/probe-verdict.mjs';
const entry='test/harness-formatting.ts';
const run=args=>{const r=spawnSync('node_modules/scriptc/bin/scriptc.exe',args,{encoding:'utf8',timeout:600000,maxBuffer:32*1024*1024});return {status:r.status,signal:r.signal,error:r.error?{code:r.error.code,message:r.error.message}:null,stdout:r.stdout??'',stderr:r.stderr??''};};
const build=run(['build',entry,'--tier','static-only','-o','build/native/harness-formatting.exe']),coverage=run(['coverage',entry]),success={status:0,signal:null,error:null,stdout:''};
const row={entry,build,coverage,verdict:probeVerdict({build,coverage,node:success,native:success})};
writeFileSync(import.meta.dirname+'/driver-gate.json',JSON.stringify(row,null,2)+'\n');
console.log(row.verdict,coverage.stdout);assert.equal(row.verdict,'PASS',JSON.stringify(row));
