import {spawnSync} from 'node:child_process';
import {writeFileSync,readFileSync} from 'node:fs';
import {resolve} from 'node:path';
const here=import.meta.dirname,root=resolve(here,'../../..');
const args=['coverage','src/script-observation-driver.ts','--explain-dynamic'];
const p=spawnSync(resolve(root,'node_modules/scriptc/bin/scriptc.exe'),args,{cwd:root,encoding:'utf8',timeout:120000,maxBuffer:8e6});
writeFileSync(resolve(here,'dynamic-explanation.json'),JSON.stringify({args,status:p.status,signal:p.signal,error:p.error?.message??null,stdout:p.stdout,stderr:p.stderr},null,2)+'\n',{flag:'wx'});
const gates=JSON.parse(readFileSync(resolve(here,'native-build-results.json')));
writeFileSync(resolve(here,'build-failure-summary.json'),JSON.stringify(gates.map(g=>({entry:g.entry,verdict:g.verdict,zigInstallationFailure:g.build.stderr.includes('unable to find zig installation directory'),coverage:g.coverage})),null,2)+'\n',{flag:'wx'});
console.log(p.stdout,p.stderr);
