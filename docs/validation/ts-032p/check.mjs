const bytes = readFileSync(new URL('corpus.txt', here));
assert.equal(createHash('sha256').update(bytes).digest('hex'), '9102f9fe83fc37b2b883a55e29c9ec173e4c0d54118eaf96113a166702dc1c6d');
const rows = bytes.toString().trimEnd().split('\n');
assert.equal(rows.length, 13350);
const view = new DataView(new ArrayBuffer(8));
const fromHex = hex => { view.setBigUint64(0, BigInt('0x' + hex)); return view.getFloat64(0); };

// Independent extraction for the NEW selection calculation: common denominator
// and half-gaps, rather than oracle neighbour rational addition/scaledBounds.
function interval(hex) {
    const bits = BigInt('0x' + hex), fraction = bits & ((1n << 52n) - 1n);
    const biased = Number(bits >> 52n);
    const f = biased === 0 ? fraction : fraction + (1n << 52n);
    const e = (biased === 0 ? 1 : biased) - 1075;
    const unequal = biased > 1 && fraction === 0n;
    const factor = unequal ? 4n : 2n;
    const unit = e >= 0 ? 1n << BigInt(e) : 1n;
    return { r: f * factor * unit, d: e >= 0 ? factor : factor << BigInt(-e),
        lo: unit, hi: unequal ? unit * 2n : unit, closed: f % 2n === 0n };
}

function select(hex, radix, k) {
    const { r, d, lo, hi, closed } = interval(hex), b = BigInt(radix);
    // Exact magnitude, deliberately no logarithm or host formatter.
    let n0 = 0, scaledR = r, scaledD = d;
    while (scaledR >= scaledD) { scaledD *= b; n0++; }
    while (scaledR * b < scaledD) { scaledR *= b; n0--; }
    let best;
    const lower = b ** BigInt(k - 1), upper = b ** BigInt(k) - 1n;
    for (const n of [n0 - 1, n0, n0 + 1]) {
        const e = n - k;
        const p = e >= 0 ? b ** BigInt(e) : 1n;
        const q = e < 0 ? b ** BigInt(-e) : 1n;
        const floor = r * q / (d * p);
        for (const raw of [floor, floor + 1n]) {
            const s = raw < lower ? lower : raw > upper ? upper : raw;
            const value = s * p * d;
            const left = (r - lo) * q, right = (r + hi) * q;
            if (closed ? value < left || value > right : value <= left || value >= right) continue;
            const delta = value - r * q, distance = delta < 0n ? -delta : delta;
            const order = best ? distance * best.q - best.distance * q : -1n;
            if (order < 0n || (order === 0n && s % 2n === 0n && best.s % 2n !== 0n)) best = { s, n, q, distance };
            else if (order === 0n && (s !== best.s || n !== best.n)) {
                assert.notEqual(s % 2n, best.s % 2n, 'unresolved same-parity tie');
            }
        }
    }
    assert.ok(best);
    return best;
}

let corrected = 0, maxK = 0;
for (const row of rows) {
    const [hex, base] = row.split(' '), radix = Number(base), x = fromHex(hex);
    const ff = freeFormat(x, radix), answer = shortest(x, radix);
    const chosen = select(hex, radix, ff.k);
    assert.equal(ff.k, answer.k);
    assert.equal(chosen.s, answer.recommended.s);
    assert.equal(chosen.n, answer.recommended.n);
    if (chosen.s !== ff.s || chosen.n !== ff.n) corrected++;
    maxK = Math.max(maxK, ff.k);
}
assert.equal(corrected, 7);

// Fixed expectations are checked, never regenerated by this script.
const vectors = JSON.parse(readFileSync(new URL('vectors.json', here)));
for (const v of vectors) {
    const x = fromHex(v.bits), answer = shortest(x, v.radix);
    assert.equal(format(answer.recommended.s, answer.recommended.n, answer.k, v.radix), v.expected);
    assert.equal(answer.k, v.k);
    assert.equal(answer.recommended.n, v.n);
    assert.equal(answer.recommended.s.toString(), v.s);
    assert.ok(judge(x, v.radix, v.expected, answer).recommended);
}
const summary = { node: process.version, pairs: rows.length, newSelectorMatches: rows.length,
    correctedCrossPowerCases: corrected, maxK, literalVectors: vectors.length,
    productionBackendRun: false, nativeBuildRun: false };
if (process.argv.includes('--record')) writeFileSync(new URL('checks.json', here), JSON.stringify(summary, null, 2) + '\n');
console.log(JSON.stringify(summary, null, 2));
