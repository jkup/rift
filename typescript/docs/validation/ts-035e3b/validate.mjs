import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,readdirSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {join} from 'node:path';
const here=import.meta.dirname,{sandbox}=JSON.parse(readFileSync(join(here,'run-location.json'))),results=[];
function run(name,args,timeout=3600000){
 console.log('START '+name);
 const r=spawnSync(process.execPath,args,{cwd:sandbox,encoding:'utf8',maxBuffer:64e6,timeout});
 writeFileSync(join(here,name+'.txt'),(r.stdout??'')+(r.stderr??''),{flag:'wx'});
 results.push({name,args,status:r.status,signal:r.signal,error:r.error?.message??null});
 writeFileSync(join(here,'suite-results.json'),JSON.stringify(results,null,2)+'\n');
 console.log('END '+name+' '+r.status);assert.equal(r.status,0,name);assert.equal(r.signal,null);assert.equal(r.error,undefined);
}
run('producer',['--test','tools/test262/script-producer.test.mjs']);
for(const lane of ['node','native'])run('guest-'+lane,['tools/run-guests.mjs',lane]);
run('A-serializers',['docs/validation/ts-035a/capture.mjs']);
run('A-decoders',['--test','tools/test262/script-result.test.mjs','tools/test262/script-driver-result.test.mjs']);
run('E3a',['--test','tools/test262/script-compose.test.mjs']);
run('C-codec',['--test','tools/test262/script-observe-codec.test.mjs']);
run('C-transport',['tools/test262/script-observation.integration.mjs']);
run('C-live',['--test','tools/test262/script-observe-live-codec.test.mjs']);
for(const n of [8,7,6,5,4,3,2,1])run('D'+n+'-source',['docs/validation/ts-035d'+n+'/validate.mjs']);
for(const [n,name] of [[8,'lexical-statement'],[6,'assignment-target'],[4,'strict-parameter'],[2,'strict-rule']])run('D'+n+'-wire',['--test','tools/test262/script-'+name+'-dispatch.test.mjs']);
for(const n of [4,2,1])run('D'+n+'-controls',['docs/validation/ts-035d'+n+'/'+(n===4?'controls':'extra-controls')+'.mjs']);
const gates=JSON.parse(readFileSync(join(sandbox,'build/native-build-results.json')));
for(const [scope,entry] of [['ts-035b','test/script-throw-inspection.ts'],['ts-034h7','test/harness-bundle.ts']])writeFileSync(join(sandbox,'docs/validation/'+scope+'/gate.json'),JSON.stringify(gates.find(g=>g.entry===entry),null,2)+'\n');
run('B-inspection',['docs/validation/ts-035b/validate.mjs']);
run('B-boundary',['docs/validation/ts-035b/boundary.mjs']);
run('H7',['docs/validation/ts-034h7/validate.mjs']);
run('host73',['--test',...readdirSync(join(sandbox,'tools/test262')).filter(n=>n.endsWith('.test.mjs')&&!n.startsWith('script-')).map(n=>'tools/test262/'+n)]);
run('observations22',['tools/test262/observation.integration.mjs']);
run('runner20',['--test','tools/probe-verdict.test.mjs']);
run('typecheck',['node_modules/typescript/bin/tsc','-p','tsconfig.json','--noEmit']);
run('probes10',['tools/run-probes.mjs']);
for(const row of JSON.parse(readFileSync(join(here,'copied-inputs.json'))))assert.equal(createHash('sha256').update(readFileSync(row.path)).digest('hex'),row.sha256,row.path);
console.log('PASS; original copied inputs unchanged');
