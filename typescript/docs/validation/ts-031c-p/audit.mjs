import { readFile, writeFile, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { join, resolve } from 'node:path';
import assert from 'node:assert/strict';
import { cases } from './cases.mjs';
const here=fileURLToPath(new URL('.',import.meta.url)),root=resolve(here,'../../..');
const git=(...args)=>execFileSync('git',args,{cwd:root,encoding:'utf8'}).trim();
const protectedPaths=['src','test','tools','fixtures','probes','package.json','package-lock.json','tsconfig.json'];
// Accepted companion radix additions are outside the engine and explicitly excluded
// from this baseline check; all src/test/tools/probes/build-config are protected.
const changed=git('diff','5b42393','--name-only','--',...protectedPaths.filter(x=>x!=='fixtures'));
assert.equal(changed,'','engine/test/tool/config changed since accepted transport');
assert.equal(git('diff','c4c2488','--name-only','--','fixtures'),'','fixture/companion changes by this task');
const hashes={};for(const name of (await readdir(join(root,'src'))).filter(x=>x.endsWith('.ts')).sort()) hashes[name]=createHash('sha256').update(await readFile(join(root,'src',name))).digest('hex');
const results=JSON.parse(await readFile(join(here,'results.json'),'utf8'));
const metadata=JSON.parse(await readFile(join(here,'metadata-results.json'),'utf8'));
assert.equal(cases.length,50);assert.equal(results.rows.length,58);assert.equal(metadata.length,6);
assert.equal(new Set(results.rows.map(x=>x.id)).size,58);
for(const row of results.rows){
 assert.deepEqual(row.lanes.node,row.lanes.native);
 assert.notEqual(row.lanes.node.record.observation.kind,'syntax-error');
 assert.equal(row.lanes.node.record.bodyEvaluated,false);
}
const literal=new Map(cases.map(x=>[x[0],x[1]]));
const table=['# Literal current behavior: measured on both existing lanes','','Generated by audit.mjs from checked results; no future expected result is a measurement.',
 'For every row: parser-observation, exit 0, empty stdout/stderr, bodyEvaluated false.',
 'Rift normal means subset parse accepted; V8 accepted means Script compilation only.','',
 '| ID | Exact synthetic source or pinned identity | Rift kind / capability (both lanes) | Location | V8 reference compile |',
 '|---|---|---|---|---|'];
for(const row of results.rows){const record=row.lanes.node.record;
 const source=row.synthetic?'`'+JSON.stringify(literal.get(row.id)).replaceAll('|','\\|').replaceAll('`','&#96;')+'`':`[${row.path}](https://github.com/tc39/test262/blob/${results.revision}/${row.path}) (${row.variant})`;
 table.push(`| ${row.id} | ${source} | ${record.observation.kind}${record.observation.capabilityCode?' / '+record.observation.capabilityCode:''} | ${record.location?record.location.line+':'+record.location.column:'null'} | ${row.reference.outcome} |`);
}
await writeFile(join(here,'current-matrix.md'),table.join('\n')+'\n');
await writeFile(join(here,'preservation.json'),JSON.stringify({head:git('rev-parse','HEAD'),acceptedTransport:'5b42393',protectedPaths,engineChanges:changed,srcSha256:hashes,counts:{synthetic:50,pinnedVariants:8,riftParserObservations:116,referenceCompilations:58,metadataObservations:6},limitations:'Existing binaries; no rebuild/full guest/probe run; no admission or conformance claims'},null,2)+'\n');
console.log('Preservation and 58-row literal matrix verified; 5b42393 engine/test/tools/config unchanged; c4c2488 fixtures unchanged.');
