import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';
import {blockers} from '../../../tools/test262/input.mjs';
const repo=fileURLToPath(new URL('../../../../',import.meta.url));
const base='e927eb6',prefix='typescript/docs/validation/ts-033e4/';
const git=(...args)=>execFileSync('git',args,{cwd:repo,encoding:'utf8',maxBuffer:32*1024*1024}).trimEnd();
const read=p=>readFileSync(join(repo,p));
const hash=b=>createHash('sha256').update(b).digest('hex');
const json=p=>JSON.parse(read(p));
const changed=git('diff','--name-only',base).split('\n').filter(Boolean);
assert.ok(changed.every(p=>p=== 'typescript/TASKS.md'||p==='typescript/COORDINATION.md'||p.startsWith(prefix)),changed.join('\n'));
const untracked=git('ls-files','--others','--exclude-standard').split('\n').filter(Boolean);
assert.ok(untracked.every(p=>p.startsWith(prefix)),untracked.join('\n'));
const heading='### TS-033E4 — Atomic internal Script activation';
assert.equal(read('typescript/TASKS.md').toString().replaceAll('\r\n','\n').split(heading)[0],git('show',base+':typescript/TASKS.md').split(heading)[0]);
const copies=['execution-matrix.md','setup-matrix.md','accessor-matrix.md','activation-matrix.md','restricted-traces.json'].map(file=>{
    const original='typescript/docs/validation/ts-033e4-p/'+file;
    assert.deepEqual(read(prefix+file),read(original));
    return {file,sha256:hash(read(prefix+file))};
});
const inheritedRows=read(prefix+'execution-matrix.md').toString().split(/\r?\n/).filter(s=>/^\| [PGLTFCRU]\d\d \|/.test(s));
assert.equal(inheritedRows.length,55);
const activationRows=read(prefix+'activation-matrix.md').toString().split(/\r?\n/).filter(s=>/^\| A\d\d \|/.test(s));
assert.equal(activationRows.length,18);
assert.equal(json(prefix+'restricted-traces.json').rows.length,13);
assert.match(read(prefix+'accessor-matrix.md').toString(),/\| R36 \|/);
for(let n=4;n<=9;n++)assert.match(inheritedRows.join('\n'),new RegExp('\\| F0'+n+' \\|'));
const inherited=['guest-node-results.json','guest-native-results.json','native-build-results.json'].map(file=>{
    const path='typescript/docs/validation/ts-033er-b/'+file,rows=json(path);
    return {path,sha256:hash(read(path)),count:rows.length,inventory:rows.map(r=>r.entry??{name:r.name,expected:r.expected})};
});
assert.deepEqual(inherited.map(r=>r.count),[212,212,48]);
const manifest=json('typescript/fixtures/assistance/test262-starter-corpus/manifest.json');
const variants=manifest.entries.flatMap(e=>e.variants.map(variant=>({id:e.id,variant,blockers:blockers({flags:e.flags,features:e.features,negative:e.negative??null,locale:[]},variant,e.id)})));
assert.equal(variants.length,60);assert.ok(variants.every(v=>v.blockers.length));
const paths=git('ls-tree','-r','--name-only',base).split('\n').filter(p=>p!=='typescript/TASKS.md'&&p!=='typescript/COORDINATION.md');
const sources=paths.filter(p=>/^typescript\/(src|test)\//.test(p)).map(path=>({path,sha256:hash(read(path))}));
const result={base:git('rev-parse',base),kind:'preservation only; no activation or full-suite execution claim',protectedFiles:paths.length,sources,copies,inherited,variants};
writeFileSync(new URL('audit.json',import.meta.url),JSON.stringify(result,null,2)+'\n');
console.log(`PASS ${paths.length} protected files, ${sources.length} source/test hashes; 55 inherited rows, A01-A18, 13 traces; retained 212/212/48; 60 blocked`);
